/* Run against the deterministic Phase 2C injected provider server tests/web/serve_forecasts.py. */
const {chromium}=require('../../.local-tools/node_modules/playwright');
const assert=require('node:assert/strict');
const base=process.env.UI_BASE_URL || 'http://127.0.0.1:8002';
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:390,height:844},permissions:['clipboard-read','clipboard-write']});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  let checks=0;
  const check=(value,message)=>{assert.ok(value,message);checks++};
  const result=()=>page.waitForSelector('#resultContent:not(.hidden)');
  await page.goto(base);await page.waitForSelector('.city-card');
  check(!await page.locator('#demo').isChecked(),'live is default');
  check(!await page.locator('.demo-tools').isVisible(),'normal UI hides fixture controls');
  check(!(await page.locator('.city-card').first().textContent()).includes('获取于'),'cards omit repeated timestamps');
  let cityResolutions=0;
  page.on('request',request=>{if(new URL(request.url()).pathname==='/api/city')cityResolutions++});
  // No selected personal city: hold advice to inspect trusted loading context.
  const featuredName=await page.locator('.city-card').first().textContent();
  let releaseAdvice, markAdviceRequested;
  const adviceRequested=new Promise(resolve=>markAdviceRequested=resolve);
  await page.route('**/api/advice?*',async route=>{
    await new Promise(resolve=>{releaseAdvice=resolve;markAdviceRequested()});await route.continue();
  });
  await page.locator('.city-card').first().click();
  await page.waitForFunction(()=>document.querySelector('#result').getAttribute('aria-busy')==='true');
  const loadingCity=await page.locator('#resultCity').textContent();
  check(loadingCity.includes('Berlin')&&featuredName.includes('Berlin'),'featured loading reuses snapshot identity');
  check(cityResolutions===0,'featured card makes zero city resolution calls without personal selection');
  await adviceRequested;
  assert.ok(releaseAdvice,'featured advice requested without geocoding');
  releaseAdvice();await result();
  check(cityResolutions===0,'featured success makes zero city resolution calls');
  await page.unroute('**/api/advice?*');
  await page.reload();await result();
  check(cityResolutions===0,'direct featured reload makes zero city resolution calls');
  await page.locator('#back').click();await page.waitForSelector('.city-card');
  await page.route('**/api/advice?*',route=>route.fulfill({status:503,json:{code:'temporarily_unavailable',error:'服务暂不可用，请重试。'}}));
  await page.locator('.city-card').nth(1).click();
  await page.getByRole('button',{name:'重试查询',exact:true}).waitFor();
  check((await page.locator('#resultCity').textContent()).includes('München'),'featured failure retains its own snapshot identity');
  check(cityResolutions===0,'featured failure makes zero city resolution calls');
  await page.unroute('**/api/advice?*');
  await page.locator('#back').click();await page.waitForSelector('.city-card');

  if (!process.argv.includes('--check-only')) await page.screenshot({path:'docs/verification/phase2c/featured-injected-mobile.png',fullPage:true});
  await page.locator('#city').fill('frankfurt');await page.waitForSelector('#cityOptions button');
  check(await page.locator('#cityOptions button').count()===2,'German namesakes shown separately');
  await page.goto(base+'/?view=trip&city_id=berlin&start=2026-10-16&end=2026-10-18&preference=hot');await result();
  check(cityResolutions===1,'direct personal link still resolves validated city metadata');
  check((await page.locator('#resultKind').textContent()).includes('真实气温'),'live result label');
  const source=await page.locator('#source').textContent();
  check(source.includes('Open-Meteo')&&source.includes('天气获取时间：2026')&&source.includes('建议生成时间：2026'),'separate acquisition and generation labels');
  check(!source.includes('模拟'),'live source never simulated');
  check((await page.locator('#spanText').textContent()).includes('2026-10-17偏冷'),'real derived outlier date');
  check(await page.evaluate(()=>Boolean(document.querySelector('#spanRemind').compareDocumentPosition(document.querySelector('#resultLayers'))&Node.DOCUMENT_POSITION_FOLLOWING)),'variation immediately before layers');
  await page.locator('#copyAdvice').click();check(!(await page.evaluate(()=>navigator.clipboard.readText())).includes('演示数据'),'copied live advice not fixture');
  await page.locator('#shareTrip').click();check(await page.evaluate(()=>navigator.clipboard.readText())===page.url(),'live share keeps trip params');
  await page.reload();await result();await page.locator('#back').click();await page.waitForSelector('.city-card');
  check((await page.locator('#city').inputValue()).includes('Berlin'),'return restores direct trip');
  await page.locator('.city-card').first().click();await result();
  check((await page.locator('#resultKind').textContent()).includes('真实气温'),'featured uses shared source');
  check((await page.locator('#source').textContent()).includes('天气获取时间：2026'),'featured carries observed acquisition');
  check((await page.locator('#resultDates').textContent()).includes('今起14天'),'featured uses complete 14-day range');
  await page.locator('#shareTrip').click();
  check(await page.evaluate(()=>navigator.clipboard.readText())===base+'/?view=city&city_id=berlin','city share has its own parameters');
  await page.locator('#copyAdvice').click();
  check((await page.evaluate(()=>navigator.clipboard.readText())).includes('城市穿衣参考'),'city copied advice isolated');
  if (!process.argv.includes('--check-only')) await page.screenshot({path:'docs/verification/phase2c/city-injected-mobile.png',fullPage:true});
  await page.reload();await result();
  check((await page.locator('#resultKind').textContent()).includes('真实气温'),'city reload remains real');
  await page.locator('#back').click();await page.waitForSelector('.city-card');
  check(await page.locator('#start').inputValue()==='2026-10-16','featured leaves personal dates');
  check(await page.locator('[data-feeling=hot]').getAttribute('aria-pressed')==='true','featured preserves personal preference');
  await page.goBack();await result();
  check(new URL(page.url()).searchParams.get('view')==='city','browser back restores city entry');
  await page.locator('#back').click();await page.waitForSelector('.city-card');
  check(await page.locator('[data-feeling=hot]').getAttribute('aria-pressed')==='true','browser history preserves personal preference');
  await page.goto(base+'/?view=trip&city_id=berlin&start=2026-10-16&end=2026-10-30&preference=normal');
  await page.waitForSelector('#resultStatus button');
  check((await page.locator('#resultStatus').textContent()).includes('五年'),'beyond 14 days unavailable');
  check(!await page.locator('#resultContent').isVisible(),'no fabricated historical live advice');
  await page.goto(base+'/?view=trip&city_id=berlin&start=2026-10-16&end=2026-10-29&preference=cold');await result();
  check((await page.locator('#resultNotice').textContent()).includes('第8–14天'),'long-range uncertainty');
  for(const width of [320,375,390,430,1280]){
    await page.setViewportSize({width,height:844});
    check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`live ${width}px no overflow`);
  }
  await page.setViewportSize({width:390,height:844});
  const height=await page.evaluate(()=>document.documentElement.scrollHeight);
  await page.setViewportSize({width:390,height});
  await page.evaluate(()=>{document.activeElement.blur();window.scrollTo({top:0,behavior:'instant'});return new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))});
  if (!process.argv.includes('--check-only')) await page.screenshot({path:'docs/verification/phase2c/live-injected-mobile.png',fullPage:false});
  await page.route('**/api/advice?*',route=>route.fulfill({status:503,json:{error:'上游超时，暂不可用'}}));
  await page.reload();await page.waitForSelector('#resultStatus button');
  check(!await page.locator('#resultContent').isVisible(),'upstream failure hides answer');
  check((await page.locator('#resultStatus').textContent()).includes('超时'),'clear unavailable state');
  check(errors.length===0,'no JS errors');
  console.log(`${checks} live browser checks passed`);await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
